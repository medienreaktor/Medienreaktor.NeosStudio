import { apiErrorDescription } from '../../http/errors'
import { api, unwrap } from '../client'
import type {
  Node,
  NodeAddress,
  NodeCopy,
  NodeCreate,
  NodeMove,
  NodeTypeChange,
  NodeVariantCreate,
} from '../schema'
import { nodePathParams, subgraphOf } from './nodes'

/**
 * Node writes against Neos.Api - one function per operation. Each takes the
 * address of the node it acts on; its workspace and dimension space point
 * become the operation's workspaceName and dimensionSpacePoint. Every write
 * is one content repository command (or a server-side sequence, e.g. a
 * variant with its ancestors) - there is no batch, see runSequentially for
 * operations on several nodes.
 */

const NODE = '/cr/{contentRepositoryId}/nodes/{nodeAggregateId}'

/** The path and query parameters of a write to the node, in its subgraph. */
function nodeParams(address: NodeAddress) {
  return { path: nodePathParams(address), query: subgraphOf(address) }
}

/** References by name as Neos.Api writes them, from target aggregate ids. */
function referencesBody(
  references: Record<string, string[]>,
): Record<string, { nodeAggregateId: string }[]> {
  return Object.fromEntries(
    Object.entries(references).map(([name, targets]) => [
      name,
      targets.map((nodeAggregateId) => ({ nodeAggregateId })),
    ]),
  )
}

/**
 * Sets the given properties (SetNodeProperties). Values travel in the form
 * Neos.Api reads them (an asset as {id}), unchanged; null unsets one. A
 * shine-through node is a 409 - create a variant first.
 */
export function setNodeProperties(
  address: NodeAddress,
  properties: Record<string, unknown>,
): Promise<Node> {
  return unwrap(
    api.PATCH(`${NODE}/properties`, {
      params: nodeParams(address),
      body: properties,
    }),
  )
}

/**
 * Replaces the references of the given names (SetNodeReferences): each list
 * of target aggregate ids replaces all references of its name, in order; an
 * empty list removes them.
 */
export async function setNodeReferences(
  address: NodeAddress,
  references: Record<string, string[]>,
): Promise<void> {
  await unwrap(
    api.PATCH(`${NODE}/references`, {
      params: nodeParams(address),
      body: referencesBody(references),
    }),
  )
}

/**
 * Creates a variant of the node, read at its address (a shine-through node
 * contributes the content it shows), in the target dimension space point
 * (CreateNodeVariant). The server varies what the variant needs along with
 * it: a tethered node's nearest non-tethered ancestor, the ancestors not in
 * the target point yet (top-down) and, with copyContent, the content below
 * it.
 */
export function createNodeVariant(
  address: NodeAddress,
  dimensionSpacePoint: string,
  copyContent = false,
): Promise<Node> {
  return unwrap(
    api.POST(`${NODE}/variants`, {
      params: nodeParams(address),
      body: {
        dimensionSpacePoint,
        ...(copyContent ? { copyContent: true } : {}),
      } satisfies NodeVariantCreate,
    }),
  )
}

export interface CreateNodeOptions {
  nodeType: string
  /** The parent; its subgraph is where the node is created. */
  parent: NodeAddress
  /** The sibling to insert before; null appends. */
  succeedingSiblingNodeAggregateId: string | null
  /** The new node's aggregate id, generated by the server if omitted. */
  nodeAggregateId?: string
  properties?: Record<string, unknown>
  /** Target aggregate ids by reference name. */
  references?: Record<string, string[]>
}

/**
 * Creates a node below the parent, originating in the parent's dimension
 * space point (CreateNodeAggregateWithNode).
 */
export function createNode(options: CreateNodeOptions): Promise<Node> {
  const body: NodeCreate = {
    nodeType: options.nodeType,
    parentNodeAggregateId: options.parent.nodeAggregateId,
    succeedingSiblingNodeAggregateId: options.succeedingSiblingNodeAggregateId,
  }
  if (options.nodeAggregateId) body.nodeAggregateId = options.nodeAggregateId
  if (options.properties && Object.keys(options.properties).length > 0) {
    body.properties = options.properties
  }
  if (options.references && Object.keys(options.references).length > 0) {
    body.references = referencesBody(options.references)
  }
  return unwrap(
    api.POST('/cr/{contentRepositoryId}/nodes', {
      params: {
        path: { contentRepositoryId: options.parent.contentRepositoryId },
        query: subgraphOf(options.parent),
      },
      body,
    }),
  )
}

/**
 * Copies the node (read in its dimension space point, in the target parent's
 * workspace) with everything below it below the target parent, before the
 * succeeding sibling (null appends), originating in the target parent's
 * dimension space point. Resolves with the copy.
 */
export function copyNode(
  source: NodeAddress,
  targetParent: NodeAddress,
  succeedingSiblingNodeAggregateId: string | null,
): Promise<Node> {
  return unwrap(
    api.POST(`${NODE}/copy`, {
      params: nodeParams({
        ...source,
        workspaceName: targetParent.workspaceName,
      }),
      body: {
        parentNodeAggregateId: targetParent.nodeAggregateId,
        succeedingSiblingNodeAggregateId,
        targetDimensionSpacePoint: targetParent.dimensionSpacePoint,
      } satisfies NodeCopy,
    }),
  )
}

/**
 * Moves the node below the new parent (null keeps the parent), before the
 * succeeding sibling (null appends). How far the move reaches into other
 * dimension space points is up to the node type's options.moveNodeStrategy
 * (gatherAll by default).
 */
export async function moveNode(
  address: NodeAddress,
  parentNodeAggregateId: string | null,
  succeedingSiblingNodeAggregateId: string | null,
): Promise<void> {
  await unwrap(
    api.POST(`${NODE}/move`, {
      params: nodeParams(address),
      body: {
        parentNodeAggregateId,
        succeedingSiblingNodeAggregateId,
      } satisfies NodeMove,
    }),
  )
}

/**
 * Sets a subtree tag on the node, in its dimension space point and the ones
 * falling back to it (TagSubtree) - "disabled" hides it.
 */
export async function tagNode(
  address: NodeAddress,
  tag: string,
): Promise<void> {
  await unwrap(
    api.PUT(`${NODE}/tags/{tag}`, {
      params: {
        path: { ...nodePathParams(address), tag },
        query: subgraphOf(address),
      },
    }),
  )
}

/** Removes a subtree tag set on the node (UntagSubtree). */
export async function untagNode(
  address: NodeAddress,
  tag: string,
): Promise<void> {
  await unwrap(
    api.DELETE(`${NODE}/tags/{tag}`, {
      params: {
        path: { ...nodePathParams(address), tag },
        query: subgraphOf(address),
      },
    }),
  )
}

/**
 * Deletes the node in its dimension space point and the ones falling back to
 * it - a soft removal (tagged "removed"), restorable until published.
 */
export async function deleteNode(address: NodeAddress): Promise<void> {
  await unwrap(api.DELETE(NODE, { params: nodeParams(address) }))
}

/**
 * Restores a removed (deleted) node in its workspace - in every dimension
 * space point, with the removed ancestor it lives inside. Undoes deleteNode
 * until it is published.
 */
export async function restoreNode(
  address: Omit<NodeAddress, 'dimensionSpacePoint'>,
): Promise<void> {
  await unwrap(
    api.POST(`${NODE}/restore`, {
      params: {
        path: {
          contentRepositoryId: address.contentRepositoryId,
          nodeAggregateId: address.nodeAggregateId,
        },
        query: { workspaceName: address.workspaceName },
      },
    }),
  )
}

/**
 * Changes the node type of the node aggregate (in all dimension space points).
 * Properties the new type does not declare are dropped, child nodes it does
 * not allow are deleted (soft).
 */
export async function changeNodeType(
  address: NodeAddress,
  nodeType: string,
): Promise<void> {
  await unwrap(
    api.PUT(`${NODE}/nodetype`, {
      params: nodeParams(address),
      body: { nodeType } satisfies NodeTypeChange,
    }),
  )
}

/**
 * Runs one write per item, in order, stopping at the first failure. Writes
 * are not transactional: if a later one fails, the earlier ones stay applied,
 * and the error says how many were (the original error is its failure).
 */
export async function runSequentially<T, R>(
  items: T[],
  write: (item: T) => Promise<R>,
): Promise<R[]> {
  const results: R[] = []
  for (const item of items) {
    try {
      results.push(await write(item))
    } catch (error) {
      if (results.length === 0) throw error
      throw new PartialWriteError(results.length, items.length, error)
    }
  }
  return results
}

/** A sequence of writes failed after some of them were applied. */
export class PartialWriteError extends Error {
  constructor(
    readonly applied: number,
    readonly total: number,
    /** The error of the write that failed. */
    readonly failure: unknown,
  ) {
    super(
      `${apiErrorDescription(failure, failure instanceof Error ? failure.message : String(failure))} (${applied} of ${total} changes were applied)`,
    )
    this.name = 'PartialWriteError'
  }
}
