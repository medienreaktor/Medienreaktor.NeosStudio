import { apiErrorDescription, apiFetch, queryString } from './client'
import type { DimensionSpacePoint } from './dimensions'
import {
  addressInWorkspace,
  decodeNodeAddress,
  nodeLocation,
} from './nodeAddress'
import { type ApiNode, type NodeDto, toNodeDto } from './nodes'

/**
 * Node writes against Neos.Api - one function per operation. Each takes the
 * encoded address of the node it acts on; the address' workspace and
 * dimension space point become the operation's workspaceName and
 * dimensionSpacePoint. Every write is one content repository command (or a
 * server-side sequence, e.g. a variant with its ancestors) - there is no
 * batch, see runSequentially for operations on several nodes.
 */

/** `{path}{suffix}?workspaceName&dimensionSpacePoint` of the node at the address. */
function nodeUrl(address: string, suffix = ''): string {
  const location = nodeLocation(address)
  return `${location.path}${suffix}${queryString({
    workspaceName: location.workspaceName,
    dimensionSpacePoint: location.dimensionSpacePoint,
  })}`
}

/**
 * Sets the given properties (SetNodeProperties). Values travel in the form
 * Neos.Api reads them (an asset as {id}), unchanged; null unsets one. A
 * shine-through node is a 409 - create a variant first.
 */
export async function setNodeProperties(
  address: string,
  properties: Record<string, unknown>,
): Promise<NodeDto> {
  return toNodeDto(
    await apiFetch<ApiNode>(nodeUrl(address, '/properties'), {
      method: 'PATCH',
      body: properties,
    }),
  )
}

/**
 * Replaces the references of the given names (SetNodeReferences): each list
 * of target aggregate ids replaces all references of its name, in order; an
 * empty list removes them.
 */
export async function setNodeReferences(
  address: string,
  references: Record<string, string[]>,
): Promise<void> {
  const body: Record<string, { nodeAggregateId: string }[]> = {}
  for (const [name, targets] of Object.entries(references)) {
    body[name] = targets.map((nodeAggregateId) => ({ nodeAggregateId }))
  }
  await apiFetch(nodeUrl(address, '/references'), { method: 'PATCH', body })
}

/**
 * Creates a variant of the node, read at its address (a shine-through node
 * contributes the content it shows), in the target dimension space point
 * (CreateNodeVariant). The server varies what the variant needs along with
 * it: a tethered node's nearest non-tethered ancestor, the ancestors not in
 * the target point yet (top-down) and, with copyContent, the content below
 * it.
 */
export async function createNodeVariant(
  address: string,
  target: DimensionSpacePoint,
  copyContent = false,
): Promise<NodeDto> {
  return toNodeDto(
    await apiFetch<ApiNode>(nodeUrl(address, '/variants'), {
      method: 'POST',
      body: {
        dimensionSpacePoint: JSON.stringify(target),
        ...(copyContent ? { copyContent: true } : {}),
      },
    }),
  )
}

export interface CreateNodeOptions {
  nodeTypeName: string
  /** Encoded address of the parent; its subgraph is where the node is created. */
  parentAddress: string
  /** Encoded address of the sibling to insert before; null appends. */
  succeedingSiblingAddress: string | null
  /** The new node's aggregate id, generated by the server if omitted. */
  nodeAggregateId?: string
  properties?: Record<string, unknown>
  references?: Record<string, string[]>
  /**
   * Creation-dialog element values - the server runs the node type's
   * nodeCreationHandlers with them (promoted elements, node templates).
   */
  elements?: Record<string, unknown>
}

/**
 * Creates a node below the parent, originating in the parent's dimension
 * space point (CreateNodeAggregateWithNode).
 */
export async function createNode(options: CreateNodeOptions): Promise<NodeDto> {
  const parent = decodeNodeAddress(options.parentAddress)
  const location = nodeLocation(options.parentAddress)
  const body: Record<string, unknown> = {
    nodeType: options.nodeTypeName,
    parentNodeAggregateId: parent.aggregateId,
  }
  if (options.succeedingSiblingAddress !== null) {
    body.succeedingSiblingNodeAggregateId = decodeNodeAddress(
      options.succeedingSiblingAddress,
    ).aggregateId
  }
  if (options.nodeAggregateId) body.nodeAggregateId = options.nodeAggregateId
  if (options.properties && Object.keys(options.properties).length > 0) {
    body.properties = options.properties
  }
  if (options.references && Object.keys(options.references).length > 0) {
    body.references = Object.fromEntries(
      Object.entries(options.references).map(([name, targets]) => [
        name,
        targets.map((nodeAggregateId) => ({ nodeAggregateId })),
      ]),
    )
  }
  if (options.elements && Object.keys(options.elements).length > 0) {
    body.elements = options.elements
  }
  return toNodeDto(
    await apiFetch<ApiNode>(
      `${location.collectionPath}${queryString({
        workspaceName: location.workspaceName,
        dimensionSpacePoint: location.dimensionSpacePoint,
      })}`,
      { method: 'POST', body },
    ),
  )
}

/**
 * Copies the node (read in its dimension space point, in the target parent's
 * workspace) with everything below it below the target parent, before the
 * succeeding sibling (null appends), originating in the target parent's
 * dimension space point. Resolves with the copy.
 */
export async function copyNode(
  sourceAddress: string,
  targetParentAddress: string,
  succeedingSiblingAddress: string | null,
): Promise<NodeDto> {
  const parent = decodeNodeAddress(targetParentAddress)
  return toNodeDto(
    await apiFetch<ApiNode>(
      nodeUrl(addressInWorkspace(sourceAddress, parent.workspaceName), '/copy'),
      {
        method: 'POST',
        body: {
          parentNodeAggregateId: parent.aggregateId,
          succeedingSiblingNodeAggregateId:
            succeedingSiblingAddress !== null
              ? decodeNodeAddress(succeedingSiblingAddress).aggregateId
              : null,
          targetDimensionSpacePoint: JSON.stringify(parent.dimensionSpacePoint),
        },
      },
    ),
  )
}

/**
 * Moves the node below the new parent, before the succeeding sibling (null
 * appends). How far the move reaches into other dimension space points is
 * up to the node type's options.moveNodeStrategy (gatherAll by default).
 */
export async function moveNode(
  address: string,
  newParentAddress: string | null,
  succeedingSiblingAddress: string | null,
): Promise<void> {
  await apiFetch(nodeUrl(address, '/move'), {
    method: 'POST',
    body: {
      parentNodeAggregateId:
        newParentAddress !== null
          ? decodeNodeAddress(newParentAddress).aggregateId
          : null,
      succeedingSiblingNodeAggregateId:
        succeedingSiblingAddress !== null
          ? decodeNodeAddress(succeedingSiblingAddress).aggregateId
          : null,
    },
  })
}

/**
 * Sets a subtree tag on the node, in its dimension space point and the ones
 * falling back to it (TagSubtree) - "disabled" hides it.
 */
export async function tagNode(address: string, tag: string): Promise<void> {
  await apiFetch(nodeUrl(address, `/tags/${encodeURIComponent(tag)}`), {
    method: 'PUT',
  })
}

/** Removes a subtree tag set on the node (UntagSubtree). */
export async function untagNode(address: string, tag: string): Promise<void> {
  await apiFetch(nodeUrl(address, `/tags/${encodeURIComponent(tag)}`), {
    method: 'DELETE',
  })
}

/**
 * Deletes the node in its dimension space point and the ones falling back to
 * it - a soft removal (tagged "removed"), restorable until published.
 */
export async function deleteNode(address: string): Promise<void> {
  await apiFetch(nodeUrl(address), { method: 'DELETE' })
}

/**
 * Changes the node type of the node aggregate (in all dimension space points).
 * Properties the new type does not declare are dropped, child nodes it does
 * not allow are deleted (soft).
 */
export async function changeNodeType(
  address: string,
  nodeTypeName: string,
): Promise<void> {
  await apiFetch(nodeUrl(address, '/nodetype'), {
    method: 'PUT',
    body: { nodeType: nodeTypeName },
  })
}

/**
 * Runs one write per item, in order, stopping at the first failure. Writes
 * are not transactional: if a later one fails, the earlier ones stay applied,
 * and the error says how many were (the original error is its failure).
 */
export async function runSequentially<T, R>(
  items: T[],
  write: (item: T) => Promise<R>,
): Promise<R[]> {
  const results: R[] = []
  for (const item of items) {
    try {
      results.push(await write(item))
    } catch (error) {
      if (results.length === 0) throw error
      throw new PartialWriteError(results.length, items.length, error)
    }
  }
  return results
}

/** A sequence of writes failed after some of them were applied. */
export class PartialWriteError extends Error {
  constructor(
    readonly applied: number,
    readonly total: number,
    /** The error of the write that failed. */
    readonly failure: unknown,
  ) {
    super(
      `${apiErrorDescription(failure, failure instanceof Error ? failure.message : String(failure))} (${applied} of ${total} changes were applied)`,
    )
    this.name = 'PartialWriteError'
  }
}
